-- รองรับการ index คู่มือแบบ "ทำต่อจากที่ค้างไว้" (resume)
--
-- ที่มา: โควตา embedding ของ Gemini free tier จำกัดที่ 100 "ชิ้นข้อความ" ต่อนาที
-- (ยืนยันด้วยการทดลองจริง: ส่ง batch ที่มี 100 รายการครั้งเดียวใช้โควตาหมดทั้งนาที
--  ส่วน batch 2 รายการหลังจากนั้นยังผ่าน — แปลว่านับเป็นรายชิ้น ไม่ใช่ต่อคำขอ)
-- คลังปัจจุบันมีประมาณ 15,700 chunk การ index ทั้งคลังจึงกินเวลาอย่างน้อย ~2 ชม. 40 นาที
--
-- ปัญหาคือเดิม indexManual ทำแบบ "ทั้งหมดหรือไม่ทำเลย" ต่อคู่มือหนึ่งเล่ม เล่มใหญ่สุด
-- (Yaskawa SGD7S, 2,258 chunk) ใช้เวลาราว 23 นาทีต่อเล่ม ถ้าล้มที่ chunk ที่ 2,000
-- ต้องเริ่มใหม่ตั้งแต่ศูนย์ทั้งหมด ซึ่งยอมรับไม่ได้กับงานที่ยาวระดับชั่วโมง
--
-- indexing_content_hash = hash ของเนื้อหาที่ "กำลัง" index อยู่ (ยังไม่เสร็จ)
--   - ถ้า indexed_content_hash ตรงกับ hash ปัจจุบัน = เล่มนี้ index ครบแล้ว ข้ามได้
--   - ถ้า indexing_content_hash ตรงกับ hash ปัจจุบัน = ค้างอยู่กลางทาง ให้ทำต่อจาก
--     chunk_index ถัดจากที่มีอยู่แล้วใน manual_chunks (ไม่ต้องลบของเดิมทิ้ง)
--   - ถ้าไม่ตรงทั้งคู่ = เนื้อหาเปลี่ยนไปจากรอบก่อน ต้องลบ chunk เดิมทิ้งแล้วเริ่มใหม่
-- เมื่อ index จบครบเล่ม จะย้ายค่าไปไว้ที่ indexed_content_hash และล้างคอลัมน์นี้เป็น null
alter table manuals add column if not exists indexing_content_hash text;

/** ขนาดไซต์อ้างอิง (กว้าง x ลึก, เมตร) ที่ `lib/plantLayout.ts` สเกลผังเข้าไป */
export const REFERENCE_SITE_SIZE: [number, number] = [190, 170];

/**
 * มุมกล้องที่ผู้ควบคุมสลับได้จาก HUD
 *   line  — ระดับสายการผลิต (ค่าเริ่มต้น) เจาะเข้า zone ที่เลือก
 *   plant — เห็นทั้งไซต์
 *   top   — มองจากด้านบนเหมือนผังพื้น
 *   eye   — ระดับสายตาคนเดินในโรงงาน
 */
export type PlantCameraPreset = "line" | "plant" | "top" | "eye";

/**
 * true = มุมที่กรอบทั้งไซต์อยู่แล้ว จึงต้องเมิน `focusBox` ทิ้ง (การซูมเข้า
 * zone ขัดกับความหมายของมุมนี้) — HUD ใช้ตัวนี้ตัดสินว่าปุ่มสลับสเกลควรพา
 * ไปมุมไหน และฉากใช้ตัดสินว่าจะรับ focusBox หรือไม่
 */
export function isWideCameraPreset(preset: PlantCameraPreset): boolean {
  return preset === "plant" || preset === "top";
}

/**
 * กล่องกลางที่กล้องควรเล็ง (พิกัดโลก, เมตร) — LiveFloorView คำนวณจากขอบเขต
 * ของ zone/อาคารที่ผู้ใช้กดใน HUD แล้วส่งให้ฉากบินไปหา
 */
export interface CameraFocusBox {
  /** จุดกลางกล่องบนแกน X (เมตร) */
  x: number;
  /** จุดกลางกล่องบนแกน Z (เมตร) */
  z: number;
  /** ความกว้างกล่องตามแกน X (เมตร) */
  width: number;
  /** ความลึกกล่องตามแกน Z (เมตร) */
  depth: number;
}
